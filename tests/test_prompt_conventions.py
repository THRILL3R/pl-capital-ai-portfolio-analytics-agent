def _mock_client(sql: str, params: list) -> MagicMock:
    client = MagicMock()
    response = MagicMock()
    response.text = json.dumps({"sql": sql, "parameters": params, "description": "mocked"})
    client.models.generate_content.return_value = response
    return client


