class TestCategoryExposureScope(unittest.TestCase):
    """Category-exposure reports: holders only by default, zero rows only on explicit request."""

    @classmethod
    def setUpClass(cls):
        cls.db = PortfolioDatabase()
        if not cls.db.is_initialized():
            cls.db.initialize_database()
        cls.instruction = GeminiSQLGenerator(client=MagicMock(), db=cls.db).build_system_instruction()

    @classmethod
    def tearDownClass(cls):
        cls.db.close()

    def _holders(self, sector: str) -> set:
        res = self.db.execute_read_only(
            "SELECT DISTINCT p.portfolio_name FROM portfolios p JOIN holdings h ON h.portfolio_id = p.portfolio_id "
            "JOIN securities s ON s.security_id = h.security_id JOIN sectors sec ON sec.sector_id = s.sector_id "
            "WHERE sec.sector_name = ?", (sector,))
        return {r["portfolio_name"] for r in res["rows"]}

    def _run(self, question: str, sql: str, sector: str):
        generator = GeminiSQLGenerator(client=_mock_client(sql, [sector]), db=self.db, model="mock-model")
        res = SQLQueryTool(db=self.db, gemini_generator=generator, use_gemini=True).execute(question)
        self.assertEqual(res["status"], "success")
        self.assertEqual(res["generation_method"], "gemini")
        self.assertFalse(res["fallback_used"])
        return res

    def test_59_prompt_forbids_zero_row_construction_and_names_explicit_triggers(self):
        self.assertIn("ONLY portfolios with at least one", self.instruction)
        self.assertIn("do NOT start from all portfolios", self.instruction)
        self.assertIn("LEFT JOIN the category aggregate", self.instruction)
        self.assertIn("do NOT use COALESCE(..., 0)", self.instruction)
        self.assertIn("ONLY when the question explicitly asks for them", self.instruction)
        self.assertIn("show zero exposure", self.instruction)
        # The rule is generic: it names no specific sector or portfolio.
        block = self.instruction[self.instruction.index("Category-exposure reports"):
                                 self.instruction.index("Sector diversification metrics")]
        for specific in ("Technology", "Fund", "Portfolio'", "13", "8 "):
            self.assertNotIn(specific, block)

    def test_60_default_category_exposure_excludes_non_holders(self):
        """Without a zero-exposure request, only portfolios holding the category are returned (any sector)."""
        for sector in ("Technology", "Healthcare", "Energy"):
            with self.subTest(sector=sector):
                res = self._run(f"For each portfolio, show the total value of {sector} sector holdings and what "
                                "percentage it represents of the total portfolio value", _INNER_CATEGORY_SQL, sector)
                names = {r["portfolio_name"] for r in res["rows"]}
                self.assertEqual(names, self._holders(sector))
                self.assertTrue(all(r["category_value"] > 0 for r in res["rows"]))
                pcts = [r["category_pct"] for r in res["rows"]]
                self.assertEqual(pcts, sorted(pcts, reverse=True))

    def test_61_explicit_zero_exposure_request_still_permits_zero_rows(self):
        """An explicit request for all portfolios including zero exposure may return zero rows."""
        res = self._run("Show Technology value and percentage for all portfolios, including portfolios with no "
                        "Technology holdings", _ALL_PORTFOLIOS_SQL, "Technology")
        total_portfolios = self.db.execute_read_only("SELECT COUNT(DISTINCT portfolio_id) AS n FROM holdings")["rows"][0]["n"]
        self.assertEqual(res["row_count"], total_portfolios)
        zero = {r["portfolio_name"] for r in res["rows"] if r["category_value"] == 0}
        self.assertTrue(zero)
        self.assertTrue(zero.isdisjoint(self._holders("Technology")))

    def test_62_safety_and_parameter_validation_still_enforced(self):
        """Unsafe or mis-parameterised category queries are rejected and fall back; nothing is written."""
        before = self.db.execute_read_only("SELECT COUNT(*) AS n FROM holdings")["rows"][0]["n"]
        cases = {
            "unsafe_sql": (_INNER_CATEGORY_SQL + "; DELETE FROM holdings", ["Technology"]),
            "forbidden_keyword": ("WITH x AS (SELECT 1) UPDATE holdings SET quantity = 0", []),
            "comment": (_INNER_CATEGORY_SQL + " -- note", ["Technology"]),
            "placeholder_mismatch": (_INNER_CATEGORY_SQL, []),
            "named_placeholder": (_INNER_CATEGORY_SQL.replace("= ?", "= :sector"), ["Technology"]),
            "bad_param_type": (_INNER_CATEGORY_SQL, [["Technology"]]),
        }
        question = ("For each portfolio, show the total value of Technology sector holdings and what percentage it "
                    "represents of the total portfolio value")
        for name, (sql, params) in cases.items():
            with self.subTest(case=name):
                generator = GeminiSQLGenerator(client=_mock_client(sql, params), db=self.db, model="mock-model")
                res = SQLQueryTool(db=self.db, gemini_generator=generator, use_gemini=True).execute(question)
                self.assertTrue(res["fallback_used"], res)
                self.assertEqual(res["generation_method"], "rule_based")
                self.assertNotIn("DELETE", res["generated_sql"] or "")
        after = self.db.execute_read_only("SELECT COUNT(*) AS n FROM holdings")["rows"][0]["n"]
        self.assertEqual(before, after)
        # Engine-level guard: even a validated connection cannot write.
        with self.assertRaises(Exception):
            self.db.get_read_only_connection().execute("DELETE FROM holdings")


