"""
Regression tests for the Gemini SQL-generation prompt conventions added after the live
gemini-3.5-flash-lite evaluation (6/10: Q5-Q8 failed).

All tests are hermetic: Gemini is replaced by a MagicMock client, so no API requests are
made. These tests check (a) that the production prompt contains the general conventions
and no hardcoded answers, and (b) that the evaluator distinguishes the failing SQL shapes
observed in the live run from SQL that follows the conventions. They do NOT measure live
Gemini accuracy.
"""

